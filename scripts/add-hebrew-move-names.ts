// Transform moves.json
const movesPath = join(__dirname, '..', 'src', 'data', 'moves.json');
const moves = JSON.parse(readFileSync(movesPath, 'utf-8'));

let translated = 0;
let fallback = 0;

for (const m of moves) {
  const he = hebrewMoves[m.id];
  const en = formatMoveName(m.name);
  if (he) {
    translated++;
  } else {
    fallback++;
  }
  m.name = {
    en,
    he: he ?? en, // fallback to English if missing
  };
}

writeFileSync(movesPath, JSON.stringify(moves, null, 2) + '\n', 'utf-8');
console.log(`Updated ${moves.length} moves in moves.json (${translated} translated, ${fallback} fallback to English)`);
