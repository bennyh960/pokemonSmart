function capitalize(s: string): string {
  return s.charAt(0).toUpperCase() + s.slice(1);
}

// Transform pokemon.json
const pokemonPath = join(__dirname, '..', 'src', 'data', 'pokemon.json');
const pokemon = JSON.parse(readFileSync(pokemonPath, 'utf-8'));

for (const p of pokemon) {
  const he = hebrewNames[p.id];
  if (!he) {
    console.warn(`Missing Hebrew name for #${p.id} ${p.name}`);
  }
  p.name = {
    en: capitalize(p.name),
    he: he ?? capitalize(p.name), // fallback to English if missing
  };
}

writeFileSync(pokemonPath, JSON.stringify(pokemon, null, 2) + '\n', 'utf-8');
console.log(`Updated ${pokemon.length} Pokemon in pokemon.json`);

// Transform evolution-chains.json
const evoPath = join(__dirname, '..', 'src', 'data', 'evolution-chains.json');
const evoChains = JSON.parse(readFileSync(evoPath, 'utf-8'));

let stageCount = 0;
for (const chain of evoChains) {
  for (const stage of chain.stages) {
    const he = hebrewNames[stage.id];
    stage.name = {
      en: capitalize(stage.name),
      he: he ?? capitalize(stage.name),
    };
    stageCount++;
  }
}

writeFileSync(evoPath, JSON.stringify(evoChains, null, 2) + '\n', 'utf-8');
console.log(`Updated ${stageCount} evolution stages in evolution-chains.json`);
